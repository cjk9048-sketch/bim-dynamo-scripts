        private sealed record Grad(double X1, double Y1, double X2, double Y2, (double Offset, string Color)[] Stops);
        private sealed record Item(string D, string? Fill, double Opacity, Grad? Gradient);

        private static readonly object Gate = new();
        private static readonly Dictionary<(string, bool), ImageSource?> Cache = new();

        /// <summary>kind 이름의 아이콘. small=true 면 16×16 단순판, 아니면 32×32. 모르는 이름·오류는 null.</summary>
        public static ImageSource? Get(string kind, bool small = false)
        {
            try
            {
                if (string.IsNullOrEmpty(kind)) return null;
                lock (Gate)
                {
                    if (Cache.TryGetValue((kind, small), out var hit)) return hit;
                    var img = Build(kind, small);
                    Cache[(kind, small)] = img;
                    return img;
                }
            }
            catch
            {
                return null;
            }
        }

        private static ImageSource? Build(string kind, bool small)
        {
            try
            {
                if (!Data.TryGetValue(small ? kind + "@16" : kind, out var items)) return null;
                double size = small ? 16 : 32;

                var inner = new DrawingGroup();
                foreach (var it in items)
                {
                    var geo = Geometry.Parse("F1 " + it.D);   // F1 = 채움 규칙 NonZero (구멍은 반대 방향 도형)
                    geo.Freeze();
                    Brush brush;
                    if (it.Gradient is { } g)
                    {
                        var lg = new LinearGradientBrush
                        {
                            StartPoint = new Point(g.X1, g.Y1),
                            EndPoint = new Point(g.X2, g.Y2),
                            MappingMode = BrushMappingMode.RelativeToBoundingBox,
                        };
                        foreach (var (off, col) in g.Stops)
                            lg.GradientStops.Add(new GradientStop((Color)ColorConverter.ConvertFromString(col), off));
                        brush = lg;
                    }
                    else
                    {
                        brush = new SolidColorBrush((Color)ColorConverter.ConvertFromString(it.Fill!));
                    }
                    brush.Opacity = it.Opacity;
                    brush.Freeze();
                    var gd = new GeometryDrawing(brush, null, geo);
                    gd.Freeze();
                    inner.Children.Add(gd);
                }
                if (small)
                {
                    var sc = new ScaleTransform(0.5, 0.5);
                    sc.Freeze();
                    inner.Transform = sc;
                }
                inner.Freeze();

                // 투명 바탕 네모 — 모든 아이콘이 같은 크기(32 또는 16)를 갖게 한다.
                var frame = new GeometryDrawing(Brushes.Transparent, null, new RectangleGeometry(new Rect(0, 0, size, size)));
                frame.Freeze();
                var outer = new DrawingGroup();
                outer.Children.Add(frame);
                outer.Children.Add(inner);
                outer.Freeze();

                var img = new DrawingImage(outer);
                img.Freeze();
                return img;
            }
            catch
            {
                return null;
            }
        }

